-- Esquema inicial da ZYCLOS.
-- Escrito em SQL portavel para rodar tanto no H2 (desenvolvimento) quanto no PostgreSQL (producao).

CREATE TABLE usuario (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           VARCHAR(100) NOT NULL,
    username       VARCHAR(30)  NOT NULL,
    email          VARCHAR(255) NOT NULL,
    senha_hash     VARCHAR(100) NOT NULL,
    avatar_url     VARCHAR(500),
    bio            VARCHAR(500),
    cidade         VARCHAR(120),
    estado         VARCHAR(2),
    papel          VARCHAR(20)  NOT NULL DEFAULT 'USUARIO',
    status         VARCHAR(20)  NOT NULL DEFAULT 'ATIVO',
    verificado     BOOLEAN      NOT NULL DEFAULT FALSE,
    criado_em      TIMESTAMP    NOT NULL,
    atualizado_em  TIMESTAMP,
    CONSTRAINT uk_usuario_email UNIQUE (email),
    CONSTRAINT uk_usuario_username UNIQUE (username)
);

CREATE TABLE preferencias_usuario (
    usuario_id            BIGINT  PRIMARY KEY,
    receber_notificacoes  BOOLEAN NOT NULL DEFAULT TRUE,
    receber_mensagens     BOOLEAN NOT NULL DEFAULT TRUE,
    perfil_publico        BOOLEAN NOT NULL DEFAULT TRUE,
    receber_novidades     BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_preferencias_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id) ON DELETE CASCADE
);

CREATE TABLE categoria (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome       VARCHAR(60) NOT NULL,
    slug       VARCHAR(60) NOT NULL,
    ativa      BOOLEAN     NOT NULL DEFAULT TRUE,
    criado_em  TIMESTAMP   NOT NULL,
    CONSTRAINT uk_categoria_nome UNIQUE (nome),
    CONSTRAINT uk_categoria_slug UNIQUE (slug)
);

CREATE TABLE anuncio (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo           VARCHAR(120)   NOT NULL,
    descricao        VARCHAR(2000)  NOT NULL,
    preco            NUMERIC(10, 2),
    categoria_id     BIGINT         NOT NULL,
    vendedor_id      BIGINT         NOT NULL,
    marca            VARCHAR(60),
    tamanho          VARCHAR(20)    NOT NULL,
    condicao         VARCHAR(30)    NOT NULL,
    estilo           VARCHAR(40),
    cidade           VARCHAR(120),
    estado           VARCHAR(2),
    tipo_negociacao  VARCHAR(20)    NOT NULL DEFAULT 'VENDA',
    status           VARCHAR(20)    NOT NULL DEFAULT 'ATIVO',
    visualizacoes    BIGINT         NOT NULL DEFAULT 0,
    criado_em        TIMESTAMP      NOT NULL,
    atualizado_em    TIMESTAMP,
    CONSTRAINT fk_anuncio_categoria FOREIGN KEY (categoria_id) REFERENCES categoria (id),
    CONSTRAINT fk_anuncio_vendedor  FOREIGN KEY (vendedor_id)  REFERENCES usuario (id)
);

CREATE INDEX ix_anuncio_status     ON anuncio (status);
CREATE INDEX ix_anuncio_categoria  ON anuncio (categoria_id);
CREATE INDEX ix_anuncio_vendedor   ON anuncio (vendedor_id);
CREATE INDEX ix_anuncio_criado_em  ON anuncio (criado_em);

CREATE TABLE anuncio_imagem (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anuncio_id  BIGINT       NOT NULL,
    url         VARCHAR(500) NOT NULL,
    principal   BOOLEAN      NOT NULL DEFAULT FALSE,
    ordem       INTEGER      NOT NULL DEFAULT 0,
    CONSTRAINT fk_imagem_anuncio FOREIGN KEY (anuncio_id) REFERENCES anuncio (id) ON DELETE CASCADE
);

CREATE INDEX ix_imagem_anuncio ON anuncio_imagem (anuncio_id);

CREATE TABLE anuncio_tag (
    anuncio_id BIGINT      NOT NULL,
    tag        VARCHAR(40) NOT NULL,
    CONSTRAINT fk_tag_anuncio FOREIGN KEY (anuncio_id) REFERENCES anuncio (id) ON DELETE CASCADE
);

CREATE INDEX ix_tag_anuncio ON anuncio_tag (anuncio_id);

CREATE TABLE favorito (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  BIGINT    NOT NULL,
    anuncio_id  BIGINT    NOT NULL,
    criado_em   TIMESTAMP NOT NULL,
    CONSTRAINT uk_favorito_usuario_anuncio UNIQUE (usuario_id, anuncio_id),
    CONSTRAINT fk_favorito_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id) ON DELETE CASCADE,
    CONSTRAINT fk_favorito_anuncio FOREIGN KEY (anuncio_id) REFERENCES anuncio (id) ON DELETE CASCADE
);

CREATE TABLE seguidor (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seguidor_id BIGINT    NOT NULL,
    seguido_id  BIGINT    NOT NULL,
    criado_em   TIMESTAMP NOT NULL,
    CONSTRAINT uk_seguidor_par UNIQUE (seguidor_id, seguido_id),
    CONSTRAINT fk_seguidor_origem  FOREIGN KEY (seguidor_id) REFERENCES usuario (id) ON DELETE CASCADE,
    CONSTRAINT fk_seguidor_destino FOREIGN KEY (seguido_id)  REFERENCES usuario (id) ON DELETE CASCADE
);

CREATE TABLE conversa (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    participante_a_id  BIGINT    NOT NULL,
    participante_b_id  BIGINT    NOT NULL,
    anuncio_id         BIGINT,
    atualizado_em      TIMESTAMP NOT NULL,
    criado_em          TIMESTAMP NOT NULL,
    CONSTRAINT uk_conversa_participantes_anuncio UNIQUE (participante_a_id, participante_b_id, anuncio_id),
    CONSTRAINT fk_conversa_a       FOREIGN KEY (participante_a_id) REFERENCES usuario (id) ON DELETE CASCADE,
    CONSTRAINT fk_conversa_b       FOREIGN KEY (participante_b_id) REFERENCES usuario (id) ON DELETE CASCADE,
    CONSTRAINT fk_conversa_anuncio FOREIGN KEY (anuncio_id)        REFERENCES anuncio (id) ON DELETE SET NULL
);

CREATE TABLE mensagem (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversa_id  BIGINT        NOT NULL,
    remetente_id BIGINT        NOT NULL,
    conteudo     VARCHAR(2000) NOT NULL,
    lida         BOOLEAN       NOT NULL DEFAULT FALSE,
    enviada_em   TIMESTAMP     NOT NULL,
    CONSTRAINT fk_mensagem_conversa  FOREIGN KEY (conversa_id)  REFERENCES conversa (id) ON DELETE CASCADE,
    CONSTRAINT fk_mensagem_remetente FOREIGN KEY (remetente_id) REFERENCES usuario (id)  ON DELETE CASCADE
);

CREATE INDEX ix_mensagem_conversa ON mensagem (conversa_id, enviada_em);

CREATE TABLE notificacao (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  BIGINT       NOT NULL,
    texto       VARCHAR(300) NOT NULL,
    tipo        VARCHAR(20)  NOT NULL DEFAULT 'SISTEMA',
    destino     VARCHAR(200),
    lida        BOOLEAN      NOT NULL DEFAULT FALSE,
    criado_em   TIMESTAMP    NOT NULL,
    CONSTRAINT fk_notificacao_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id) ON DELETE CASCADE
);

CREATE INDEX ix_notificacao_usuario ON notificacao (usuario_id, criado_em);

CREATE TABLE avaliacao (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    autor_id    BIGINT        NOT NULL,
    avaliado_id BIGINT        NOT NULL,
    anuncio_id  BIGINT,
    nota        INTEGER       NOT NULL,
    comentario  VARCHAR(1000),
    criado_em   TIMESTAMP     NOT NULL,
    CONSTRAINT ck_avaliacao_nota CHECK (nota BETWEEN 1 AND 5),
    CONSTRAINT fk_avaliacao_autor    FOREIGN KEY (autor_id)    REFERENCES usuario (id) ON DELETE CASCADE,
    CONSTRAINT fk_avaliacao_avaliado FOREIGN KEY (avaliado_id) REFERENCES usuario (id) ON DELETE CASCADE,
    CONSTRAINT fk_avaliacao_anuncio  FOREIGN KEY (anuncio_id)  REFERENCES anuncio (id) ON DELETE SET NULL
);

CREATE INDEX ix_avaliacao_avaliado ON avaliacao (avaliado_id);

CREATE TABLE proposta_troca (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proponente_id        BIGINT       NOT NULL,
    destinatario_id      BIGINT       NOT NULL,
    anuncio_desejado_id  BIGINT       NOT NULL,
    anuncio_oferecido_id BIGINT       NOT NULL,
    mensagem             VARCHAR(500),
    status               VARCHAR(20)  NOT NULL DEFAULT 'PENDENTE',
    criado_em            TIMESTAMP    NOT NULL,
    atualizado_em        TIMESTAMP,
    CONSTRAINT fk_proposta_proponente   FOREIGN KEY (proponente_id)        REFERENCES usuario (id) ON DELETE CASCADE,
    CONSTRAINT fk_proposta_destinatario FOREIGN KEY (destinatario_id)      REFERENCES usuario (id) ON DELETE CASCADE,
    CONSTRAINT fk_proposta_desejado     FOREIGN KEY (anuncio_desejado_id)  REFERENCES anuncio (id) ON DELETE CASCADE,
    CONSTRAINT fk_proposta_oferecido    FOREIGN KEY (anuncio_oferecido_id) REFERENCES anuncio (id) ON DELETE CASCADE
);

CREATE INDEX ix_proposta_destinatario ON proposta_troca (destinatario_id, status);
CREATE INDEX ix_proposta_proponente   ON proposta_troca (proponente_id, status);

CREATE TABLE denuncia (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    denunciante_id        BIGINT        NOT NULL,
    anuncio_id            BIGINT,
    usuario_denunciado_id BIGINT,
    motivo                VARCHAR(120)  NOT NULL,
    descricao             VARCHAR(1000),
    status                VARCHAR(20)   NOT NULL DEFAULT 'PENDENTE',
    resposta_moderacao    VARCHAR(1000),
    criado_em             TIMESTAMP     NOT NULL,
    resolvido_em          TIMESTAMP,
    CONSTRAINT fk_denuncia_denunciante FOREIGN KEY (denunciante_id)        REFERENCES usuario (id) ON DELETE CASCADE,
    CONSTRAINT fk_denuncia_anuncio     FOREIGN KEY (anuncio_id)            REFERENCES anuncio (id) ON DELETE SET NULL,
    CONSTRAINT fk_denuncia_usuario     FOREIGN KEY (usuario_denunciado_id) REFERENCES usuario (id) ON DELETE SET NULL
);

CREATE INDEX ix_denuncia_status ON denuncia (status, criado_em);

CREATE TABLE token_recuperacao (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT       NOT NULL,
    codigo     VARCHAR(100) NOT NULL,
    expira_em  TIMESTAMP    NOT NULL,
    usado_em   TIMESTAMP,
    CONSTRAINT uk_token_codigo UNIQUE (codigo),
    CONSTRAINT fk_token_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id) ON DELETE CASCADE
);
